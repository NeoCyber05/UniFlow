import fs, { readFileSync, writeFileSync } from "node:fs";

// shortcut: @types/node is v20 (no globSync typing), runtime is Node 22; drop cast after upgrading @types/node.
const globSync = (fs as unknown as { globSync(pattern: string): string[] }).globSync;

const entries = globSync("actions/*/*/index.ts")
  .map((f) => f.replace(/\\/g, "/"))
  .sort()
  .map((file) => {
    const match = readFileSync(file, "utf8").match(/export const (\w+) = createSafeAction/);
    if (!match) throw new Error(`${file}: no "export const X = createSafeAction"`);
    const key = file.replace(/^actions\//, "").replace(/\/index\.ts$/, "");
    return { key, name: match[1] };
  });

const out = [
  "// GENERATED by scripts/gen-action-registry.ts. Do not edit.",
  ...entries.map((e, i) => `import { ${e.name} as a${i} } from "@/actions/${e.key}";`),
  "",
  "export const actionRegistry: Record<string, (input: unknown) => Promise<unknown>> = {",
  ...entries.map((e, i) => `  "${e.key}": a${i} as (input: unknown) => Promise<unknown>,`),
  "};",
  "",
].join("\n");

writeFileSync("server/actions-registry.gen.ts", out);
console.log(`action registry: ${entries.length} actions`);
